/**
 * Builds public/icons/sprite.svg from scripts/icons/icon-set.mjs.
 *
 * The sprite is one cacheable file referenced via <use href="/icons/sprite.svg#name">,
 * so icon artwork leaves the JavaScript bundle entirely and is fetched once.
 *
 * Also reports coverage: it scans src/ for names still imported from lucide-react
 * and fails if any of them has no counterpart in the set, so the migration cannot
 * be left half-done silently.
 *
 *   node scripts/build-icons.mjs
 */

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, extname } from 'node:path';
import { createHash } from 'node:crypto';
import { ICONS, STROKE_DEFAULTS, MATERIAL_DEFAULTS, MATERIAL_ICONS, VIEWBOX } from './icons/icon-set.mjs';

const SRC = join(process.cwd(), 'src');
const OUT_DIR = join(process.cwd(), 'public', 'icons');
const OUT_FILE = join(OUT_DIR, 'sprite.svg');

/** PascalCase lucide name -> kebab-case sprite id. */
export function toKebab(name) {
    return String(name)
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
        // Trailing digits are a separate segment: BarChart3 -> bar-chart-3,
        // not bar-chart3. Lucide uses them as size/variant suffixes.
        .replace(/([A-Za-z])(\d)/g, '$1-$2')
        .toLowerCase();
}

async function walk(dir) {
    const out = [];
    for (const entry of await readdir(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name);
        if (entry.isDirectory()) out.push(...await walk(full));
        else if (['.js', '.jsx'].includes(extname(entry.name))) out.push(full);
    }
    return out;
}

async function lucideNamesInSource() {
    const names = new Set();
    for (const file of await walk(SRC)) {
        const text = await readFile(file, 'utf8');
        for (const match of text.matchAll(/import\s*\{([^}]+)\}\s*from\s*'lucide-react'/g)) {
            for (const raw of match[1].split(',')) {
                const name = raw.trim().split(/\s+as\s+/)[0].trim();
                if (name) names.add(name);
            }
        }
    }
    return [...names].sort();
}

/** kebab sprite id -> PascalCase export name. Inverse of toKebab. */
export function toPascal(kebab) {
    return String(kebab).split('-').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');
}

/*
  Paint and grid are per symbol, not per sprite.

  Material Symbols are solid shapes on a 0 -960 960 960 grid; the hand-drawn gs-*
  glyphs are 1.75 strokes on 0 0 24 24. A single set of attributes on the root
  <svg> cannot serve both — stroke defaults applied to a filled path give a
  visibly bolder, smudged glyph, and the wrong viewBox renders it off-canvas or
  invisible. Putting both on each <symbol> lets the two families coexist, and
  <use> inherits whichever one it points at.
*/
function attrsFor(name) {
    const defaults = MATERIAL_ICONS.has(name) ? MATERIAL_DEFAULTS : STROKE_DEFAULTS;
    return Object.entries(defaults).map(([k, v]) => `${k}="${v}"`).join(' ');
}

function viewBoxFor(name) {
    return MATERIAL_ICONS.has(name) ? VIEWBOX.material : VIEWBOX.stroke;
}

const symbols = Object.entries(ICONS)
    .map(([name, body]) => `<symbol id="${name}" viewBox="${viewBoxFor(name)}" ${attrsFor(name)}>${body}</symbol>`)
    .join('\n');

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols}\n</svg>\n`;

await mkdir(OUT_DIR, { recursive: true });
await writeFile(OUT_FILE, sprite, 'utf8');

/*
 * Barrel of named wrappers.
 *
 * Icons are used two ways in this codebase: as JSX tags (<Heart size={16} />) and
 * as component values passed to other components (icon={Heart}, { icon: Users }).
 * There are ~120 of the latter. Exporting one thin wrapper per name means both
 * forms keep working, so migrating off lucide-react is a change of import
 * specifier and nothing else — no call-site churn, and nothing to get wrong.
 */
const barrel = [
    '// GENERATED by scripts/build-icons.mjs - do not edit by hand.',
    '//',
    '// Named icon components backed by the self-hosted sprite. Import these instead',
    '// of lucide-react. Each is a thin wrapper around <Icon>, so both JSX usage and',
    '// value usage (icon={Heart}) behave exactly as before.',
    '//',
    '// Add or edit artwork in scripts/icons/icon-set.mjs, then re-run the builder.',
    '',
    "import Icon from '@/components/Icon';",
    '',
    ...Object.keys(ICONS).map((name) =>
        `export const ${toPascal(name)} = (props) => <Icon name="${name}" {...props} />;`),
    '',
].join('\n');

await writeFile(join(process.cwd(), 'src', 'components', 'icons.js'), barrel, 'utf8');

/*
  A version stamp for the sprite URL, from the sprite's own bytes.

  public/icons/* is served `immutable, max-age=31536000` because the files
  there are replaced by name and never edited. That is true of the seed and
  gift artwork and false of this file, which this script rewrites in place at
  a fixed path. So a browser or CDN that had fetched the sprite kept it for a
  year and never saw a new icon: adding `verified` shipped to production and
  the live URL still served the previous 103 symbols, four hours stale, while
  the same URL with any query string served the new 104.

  Appending the content hash gives each sprite a URL of its own, so the long
  cache keeps working and a changed sprite is simply a different address.
*/
const spriteHash = createHash('sha256').update(sprite).digest('hex').slice(0, 12);
await writeFile(
    join(process.cwd(), 'src', 'components', 'spriteVersion.js'),
    `// GENERATED by scripts/build-icons.mjs - do not edit by hand.\n`
    + `// Content hash of public/icons/sprite.svg; see that script for why.\n`
    + `export const SPRITE_VERSION = '${spriteHash}';\n`,
    'utf8',
);

const remaining = await lucideNamesInSource();
const missing = remaining.filter((name) => !ICONS[toKebab(name)]);

console.log(`Wrote ${Object.keys(ICONS).length} symbols to public/icons/sprite.svg`);
console.log(`Sprite version: ${spriteHash}`);
console.log(`Sprite size: ${(Buffer.byteLength(sprite) / 1024).toFixed(1)} KB`);

if (remaining.length) {
    console.log(`\nStill importing from lucide-react: ${remaining.length} name(s)`);
}
if (missing.length) {
    console.error(`\nNo sprite symbol for ${missing.length} name(s):`);
    for (const name of missing) console.error(`  ${name}  ->  ${toKebab(name)}`);
    process.exitCode = 1;
} else if (remaining.length) {
    console.log('Every one has a sprite symbol; run the codemod to switch call sites.');
} else {
    console.log('No lucide-react imports remain.');
}
