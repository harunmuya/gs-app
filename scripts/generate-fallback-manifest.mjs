// Regenerates src/lib/profileFallbackManifest.js from the seed photo folders.
//
// Why this exists: lib/profileImages.js used to import the full 67KB
// localSeedMembers dataset purely to build lists of fallback photo URLs. Because
// profileImages is imported by client components (UserAvatar, BlurImage, discover,
// members, matches), that shipped the entire seed roster to every visitor — both a
// bundle cost and a disclosure of the seed catalogue to anyone opening devtools.
//
// Only a handful of URLs per category are needed for an image fallback, so this
// emits a small curated manifest instead.
//
//   node scripts/generate-fallback-manifest.mjs

import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const SEED_DIR = join(process.cwd(), 'public', 'seed');
const OUT_FILE = join(process.cwd(), 'src', 'lib', 'profileFallbackManifest.js');
const PER_LABEL = 12;

const LABEL_FOLDERS = {
    sugar_mummy: 'sugarmums',
    sugar_daddy: 'sugar-dads',
    mistress: 'mistresses',
    toyboy: 'Toboys or Sugarguys',
};

const IMAGE_PATTERN = /\.(jpe?g|png|webp|avif)$/i;

/**
 * One entry per photo, preferring the WebP.
 *
 * The originals still sit beside the converted files, so a plain extension
 * filter listed each photo twice and half the fallback pool pointed at the
 * heavy JPEG — which defeats the conversion precisely where it matters, since a
 * fallback fires when the primary image has already failed to load.
 */
async function poolFor(folder) {
    const entries = await readdir(join(SEED_DIR, folder), { withFileTypes: true });
    const names = entries
        .filter((entry) => entry.isFile() && IMAGE_PATTERN.test(entry.name))
        .map((entry) => entry.name);
    const webpStems = new Set(
        names.filter((n) => /\.webp$/i.test(n)).map((n) => n.replace(/\.webp$/i, ''))
    );
    return names
        .filter((name) => /\.webp$/i.test(name) || !webpStems.has(name.replace(/\.(jpe?g|png|avif)$/i, '')))
        .sort()
        .slice(0, PER_LABEL)
        .map((name) => `/seed/${encodeURIComponent(folder)}/${encodeURIComponent(name)}`);
}

const lines = [
    '// GENERATED by scripts/generate-fallback-manifest.mjs - do not edit by hand.',
    '// A small curated pool of seed photo paths used only as an image fallback.',
    '// Replaces importing the full 67KB seed dataset into the client bundle.',
    '',
    'export const FALLBACK_PROFILE_IMAGES_BY_LABEL = {',
];

for (const [label, folder] of Object.entries(LABEL_FOLDERS)) {
    const pool = await poolFor(folder);
    lines.push(`    ${label}: [`);
    for (const url of pool) lines.push(`        '${url}',`);
    lines.push('    ],');
}

lines.push('};', '');

await writeFile(OUT_FILE, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUT_FILE}`);
